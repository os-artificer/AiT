// AnnotateJPEG draws ASCII provenance lines onto the bottom of a JPEG and rewrites path.
func AnnotateJPEG(path string, lines []string) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	img, err := jpeg.Decode(f)
	_ = f.Close()
	if err != nil {
		return err
	}

	b := img.Bounds()
	dst := image.NewRGBA(b)
	draw.Draw(dst, b, img, b.Min, draw.Src)

	clean := make([]string, 0, len(lines))
	for _, ln := range lines {
		clean = append(clean, asciiOnly(ln))
	}
	const scale = 2
	const pad = 4
	lineH := 8*scale + 2
	barH := pad*2 + lineH*len(clean)
	if barH > b.Dy()/2 {
		barH = b.Dy() / 2
	}
	bar := image.Rect(b.Min.X, b.Max.Y-barH, b.Max.X, b.Max.Y)
	draw.Draw(dst, bar, &image.Uniform{C: color.RGBA{0, 0, 0, 180}}, image.Point{}, draw.Over)

	y := b.Max.Y - barH + pad
	for _, ln := range clean {
		drawASCII(dst, pad, y, scale, ln, color.White)
		y += lineH
		if y >= b.Max.Y {
			break
		}
	}

	out, err := os.Create(path)
	if err != nil {
		return err
	}
	defer out.Close()
	return jpeg.Encode(out, dst, &jpeg.Options{Quality: 90})
}

func asciiOnly(s string) string {
	var b strings.Builder
	for _, r := range s {
		if r > 127 || (!unicode.IsPrint(r) && r != ' ') {
			b.WriteByte('?')
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

// Minimal 5x7 glyph set for A-Z a-z 0-9 and a few punctuation marks.
func drawASCII(img *image.RGBA, x, y, scale int, s string, c color.Color) {
	cx := x
	for _, r := range s {
		g, ok := glyphs[r]
		if !ok {
			g = glyphs['?']
		}
		for row := 0; row < 7; row++ {
			bits := g[row]
			for col := 0; col < 5; col++ {
				if bits&(1<<uint(4-col)) == 0 {
					continue
				}
				for dy := 0; dy < scale; dy++ {
					for dx := 0; dx < scale; dx++ {
						img.Set(cx+col*scale+dx, y+row*scale+dy, c)
					}
				}
			}
		}
		cx += 6 * scale
	}
}

